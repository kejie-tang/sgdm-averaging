#!/usr/bin/env bash
# Build the submission archive for the Code & Data Disclosure package.
#
# Usage:
#   bash scripts/make_tarball.sh            # figures + raw arrays  (~125 MB)
#   RAW=0 bash scripts/make_tarball.sh      # figures only          (~2 MB)
#   OUT=../sgdm-averaging.tar.gz bash scripts/make_tarball.sh
#
# Run from anywhere; the script finds the repository root itself.
#
# results/ is generated output and is not tracked by git (see .gitignore), but
# it goes into the archive.  RAW=0 drops the raw *.npz arrays, which are large
# and do not compress; they are regenerable with scripts/run_all.sh.

set -e
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

OUT="${OUT:-$ROOT/sgdm-averaging.tar.gz}"
RAW="${RAW:-1}"

# --- sanity checks ----------------------------------------------------------
for f in README.md LICENSE AUTHORS requirements.txt .gitignore \
         src scripts docs data/README.md data/cifar_logs; do
  if [ ! -e "$f" ]; then
    echo "ERROR: missing $f -- run this from a complete checkout." >&2
    exit 1
  fi
done

if [ ! -d results ] || [ -z "$(find results -name '*.png' -print -quit)" ]; then
  echo "ERROR: results/ has no figures. Run 'bash scripts/run_all.sh' first." >&2
  exit 1
fi

# --- optional: drop the raw arrays ------------------------------------------
NOTE=""
if [ "$RAW" != "1" ]; then
  EXCLUDES=(--exclude='*.npz')
  NOTE="results/RAW_ARRAYS_EXCLUDED.md"
  cat > "$NOTE" <<'EOF'
# Raw arrays excluded

This archive was built with `RAW=0`, so the per-replication `*.npz` arrays are
not included. Every figure in `results/` was drawn from them, and they are
regenerated by

    bash scripts/run_all.sh            # full fidelity, several hours
    FAST=1 bash scripts/run_all.sh     # reduced-fidelity quick pass

They are omitted purely for size: the eleven arrays total about 122 MB and do
not compress (they are dense float64).
EOF
fi
trap '[ -n "$NOTE" ] && rm -f "$NOTE"' EXIT

# --- build ------------------------------------------------------------------
# Excluded on purpose:
#   data/MNIST/, data/CIFAR10/  -- 295 MB of public datasets, downloaded on
#                                  demand by --download; not ours to ship
#   __pycache__/, *.pyc, .git   -- build and VCS noise
rm -f "$OUT"
# --force-local: on Windows (Git Bash / MSYS2) OUT may be a C:\... path, and
# GNU tar would otherwise read "C:" as a remote host and fail.
tar czf "$OUT" --force-local \
  --exclude='__pycache__' --exclude='*.pyc' --exclude='.git' \
  "${EXCLUDES[@]}" \
  README.md LICENSE AUTHORS requirements.txt .gitignore \
  src scripts docs \
  data/README.md data/cifar_logs \
  results

# --- verify -----------------------------------------------------------------
LIST="$(tar tzf "$OUT" --force-local)"

for bad in 'data/MNIST/' 'data/CIFAR10/' '.git/' '__pycache__'; do
  if printf '%s\n' "$LIST" | grep -qF "$bad"; then
    echo "ERROR: $bad leaked into the archive." >&2
    exit 1
  fi
done

for want in 'README.md' 'LICENSE' 'AUTHORS' 'src/sgdm_core.py' \
            'scripts/run_all.sh' 'data/cifar_logs/lr0.5_gamma0.9.csv' \
            'results/theory/fig_lambda.png'; do
  if ! printf '%s\n' "$LIST" | grep -qxF "$want"; then
    echo "ERROR: $want is missing from the archive." >&2
    exit 1
  fi
done

SIZE="$(wc -c < "$OUT")"
echo ">>> archive: $OUT"
echo ">>> size:    $(awk -v s="$SIZE" 'BEGIN {printf "%.1f MB", s/1048576}')"
echo ">>> files:   $(printf '%s\n' "$LIST" | wc -l)"
if [ "$RAW" != "1" ]; then
  echo ">>> raw *.npz arrays excluded (RAW=0); see results/RAW_ARRAYS_EXCLUDED.md"
else
  echo ">>> raw *.npz arrays included; use RAW=0 for a figure-only archive"
fi
